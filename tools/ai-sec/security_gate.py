#!/usr/bin/env python3
"""Independent AI-SEC security gate. stdlib only; does not install scanners.

Exit: 0 = every selected required scanner passed, 1 = one or more scanners
returned nonzero, 2 = incomplete (missing tool/configuration/timeout/no checks).
Never interpret a missing scanner as a pass. Runs no shell strings.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess  # nosec B404 - fixed argv lists only, shell=False
import sys
from datetime import datetime, timezone
from pathlib import Path

COMMANDS = {
    "gitleaks": lambda image, report: [
        "gitleaks",
        "dir",
        ".",
        "--config",
        ".gitleaks.toml",
        "--redact",
        "--no-banner",
    ],
    "semgrep": lambda image, report: [
        "semgrep",
        "scan",
        "--config",
        ".semgrep/nexus.yml",
        "--config",
        "p/python",
        "--config",
        "p/javascript",
        "--config",
        "p/security-audit",
        "--error",
        "--metrics",
        "off",
        "--disable-version-check",
        "app",
        "tools",
        "tests",
    ],
    "bandit": lambda image, report: [
        "bandit",
        "-q",
        "-c",
        ".bandit.yaml",
        "-r",
        "app",
        "tools",
    ],
    "osv": lambda image, report: ["osv-scanner", "scan", "source", "-r", "."],
    "checkov": lambda image, report: ["checkov", "-d", ".", "--compact"],
    "trivy_fs": lambda image, report: [
        "trivy",
        "fs",
        "--scanners",
        "vuln,misconfig,secret",
        "--severity",
        "HIGH,CRITICAL",
        "--exit-code",
        "1",
        "--skip-dirs",
        ".venv",
        "--skip-dirs",
        ".venv-security",
        "--skip-dirs",
        ".git",
        ".",
    ],
    "grype_dir": lambda image, report: [
        "grype",
        "dir:.",
        "--fail-on",
        "high",
        "--exclude",
        "./.venv",
        "--exclude",
        "./.venv-security",
        "--exclude",
        "./.git",
    ],
    "grype_image": lambda image, report: ["grype", image, "--fail-on", "high"],
    "trivy_image": lambda image, report: [
        "trivy",
        "image",
        "--scanners",
        "vuln,misconfig,secret",
        "--severity",
        "HIGH,CRITICAL",
        "--exit-code",
        "1",
        image,
    ],
    "syft_sbom": lambda image, report: ["syft", image, "-o", "cyclonedx-json"],
}
SCOPES = {
    "gitleaks": "code",
    "semgrep": "code",
    "osv": "code",
    "checkov": "code",
    "trivy_fs": "code",
    "bandit": "code",
    "grype_dir": "code",
    "grype_image": "container",
    "trivy_image": "container",
    "syft_sbom": "container",
}


def private_write(path: Path, data: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    # Never allow group-readable scan evidence on creation.
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    os.fchmod(fd, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write(data)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument(
        "--policy",
        default=".ai-sec/security-policy.json",
        help="JSON policy generated by scaffold_quality.py",
    )
    p.add_argument("--scope", choices=["code", "container", "all"], default="code")
    p.add_argument(
        "--image",
        help="EXPLICIT local image tag/digest to scan; required for container scope",
    )
    p.add_argument("--report", default=".ai-sec/reports/security-summary.json")
    p.add_argument("--timeout", type=int, default=600, help="per scanner seconds")
    p.add_argument(
        "--list", action="store_true", help="show plan and availability; do not execute"
    )
    args = p.parse_args(argv)
    if args.timeout < 1:
        p.error("timeout must be > 0")
    root = Path.cwd()
    extra = [str(root / ".venv-security" / "bin"), str(Path.home() / ".local" / "bin")]
    os.environ["PATH"] = os.pathsep.join(
        [d for d in extra if Path(d).is_dir()] + [os.environ.get("PATH", "")]
    )
    path = root / args.policy
    try:
        policy = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        print(f"INCOMPLETE: policy not readable: {exc}", file=sys.stderr)
        return 2
    if policy.get("schema_version") != 1 or not isinstance(
        policy.get("scanners"), dict
    ):
        print("INCOMPLETE: invalid policy schema", file=sys.stderr)
        return 2
    unknown = set(policy["scanners"]) - set(COMMANDS)
    if unknown:
        print(f"INCOMPLETE: unrecognized scanners: {sorted(unknown)}", file=sys.stderr)
        return 2

    result = {
        "schema_version": 1,
        "generated_utc": datetime.now(timezone.utc).isoformat(),
        "scope": args.scope,
        "image": args.image if args.scope != "code" else None,
        "checks": [],
        "commercial_integrations": "disabled; see commercial-scanner-stubs",
    }
    selected = 0
    required_selected = 0
    findings = False
    incomplete = False
    for name, scope in SCOPES.items():
        if args.scope not in (scope, "all"):
            continue
        raw = policy["scanners"].get(name, {"enabled": False, "required": False})
        if (
            not isinstance(raw, dict)
            or not isinstance(raw.get("enabled"), bool)
            or not isinstance(raw.get("required"), bool)
        ):
            print(f"INCOMPLETE: invalid scanner entry: {name}", file=sys.stderr)
            return 2
        if not raw["enabled"]:
            print(f"NOT CONFIGURED: {name}")
            continue
        selected += 1
        required_selected += int(raw["required"])
        cmd = COMMANDS[name](args.image, args.report)
        entry = {"scanner": name, "scope": scope, "required": raw["required"]}
        if scope == "container" and not args.image:
            entry["status"] = "incomplete_no_image"
            incomplete |= raw["required"]
        elif shutil.which(cmd[0]) is None:
            entry["status"] = "incomplete_missing_tool"
            incomplete |= raw["required"]
        elif args.list:
            entry["status"] = "available_not_run"
        else:
            try:
                # Scanner output may contain sensitive information; do not print or persist raw logs.
                completed = subprocess.run(  # nosec B603 - argv from COMMANDS table, not user input
                    cmd,
                    cwd=root,
                    text=True,
                    capture_output=True,
                    timeout=args.timeout,
                    check=False,
                )
                entry["exit_code"] = completed.returncode
                entry["status"] = (
                    "passed" if completed.returncode == 0 else "failed_or_findings"
                )
                findings |= bool(completed.returncode and raw["required"])
                if name == "syft_sbom" and completed.returncode == 0:
                    sbom = root / ".ai-sec/reports/sbom.cdx.json"
                    try:
                        sbom_obj = json.loads(completed.stdout)
                        if not isinstance(sbom_obj, dict) or not sbom_obj.get(
                            "bomFormat"
                        ):
                            raise ValueError("CycloneDX bomFormat missing")
                        private_write(sbom, completed.stdout)
                        entry["artifact"] = str(sbom.relative_to(root))
                    except ValueError:
                        entry["status"] = "incomplete_invalid_sbom"
                        incomplete |= raw["required"]
            except (OSError, subprocess.TimeoutExpired) as exc:
                entry["status"] = "incomplete_runtime_error"
                entry["error_type"] = type(exc).__name__
                incomplete |= raw["required"]
        print(
            f"{entry['status'].upper()}: {name}"
            + (f" (exit={entry['exit_code']})" if "exit_code" in entry else "")
        )
        result["checks"].append(entry)

    if selected == 0 or required_selected == 0:
        print(
            "INCOMPLETE: no enabled required scanners for selected scope",
            file=sys.stderr,
        )
        incomplete = True
    if args.list:
        print("PLAN ONLY: no security scanner executed; do not interpret as a pass")
        return 0
    result["result"] = (
        "failed" if findings else ("incomplete" if incomplete else "passed")
    )
    private_write(
        root / args.report, json.dumps(result, indent=2, sort_keys=True) + "\n"
    )
    print(f"Evidence: {args.report} | Result: {result['result'].upper()}")
    return 1 if findings else (2 if incomplete else 0)


if __name__ == "__main__":
    raise SystemExit(main())
